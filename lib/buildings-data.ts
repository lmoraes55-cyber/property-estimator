/**
 * Buildings Database - Dubai Residential Properties
 * Imported from assetintel_complete_dubai_residential_database.csv
 * Includes tier classification and premium calculations
 */

export interface BuildingRecord {
  name: string;
  area: string;
  tier: "ultra-luxury" | "luxury" | "mid" | "low";
  premiumPercentage: number;
  dldKey?: string;   // normalized DLD dataset key → enables live Ejari lookup
  dldArea?: string;  // DLD administrative area (e.g. "Burj Khalifa")
}

// Map CSV tiers to our system with premium percentages
const mapTierAndPremium = (
  csvTier: "High" | "Medium" | "Low-to-Medium"
): { tier: "ultra-luxury" | "luxury" | "mid" | "low"; premiumPercentage: number } => {
  switch (csvTier) {
    case "High":
      // High tier = ultra-luxury/luxury with 1-2% premium
      return { tier: "luxury", premiumPercentage: 0.6 };
    case "Medium":
      // Medium tier = mid with 0.5-1% premium
      return { tier: "mid", premiumPercentage: 0.3 };
    case "Low-to-Medium":
      // Low-to-medium = low with 0% premium
      return { tier: "low", premiumPercentage: 0 };
    default:
      return { tier: "mid", premiumPercentage: 0.5 };
  }
};

// Outskirt areas for long-term rental suggestions
// "Town Square" and "JVT" are separate communities and are listed separately.
// They were previously collapsed into one "Town Square & JVT" label, which
// resolved to the TOWN SQUARE master for everything under it — harmless while
// only Town Square buildings used it, but silently wrong for any JVT building
// added later (JVT sits in Al Barsha South Fifth, Town Square in Al Yelayiss 2).
//
// NOTE for adding JVT buildings: set `area` to "Jumeirah Village Triangle (JVT)",
// the same shape as the JBR entries. A bare "JVT" is a single token and the
// master matcher deliberately refuses those as too collision-prone, so it would
// fall through to the pooled area figure instead of the JVT community.
export const OUTSKIRT_AREAS = ["Dubai South", "JVT", "Town Square", "DAMAC Hills 2"];

/**
 * Check if an area is considered an outskirt
 */
export const isOutskirtArea = (area: string): boolean => {
  const normalizedArea = area.toLowerCase().trim();
  return OUTSKIRT_AREAS.some((a) => normalizedArea.includes(a.toLowerCase()));
};

