/**
 * Get all buildings sorted by area
 */
export const getBuildingsByArea = (area: string): BuildingRecord[] => {
  return Object.values(BUILDINGS_DATABASE).filter((b) => b.area === area);
};

/**
 * Get all unique areas
 */
export const getAllAreas = (): string[] => {
  const areas = new Set(Object.values(BUILDINGS_DATABASE).map((b) => b.area));
  return Array.from(areas).sort();
};

/**
 * Get building by name
 */
export const getBuildingByName = (name: string): BuildingRecord | undefined => {
  return BUILDINGS_DATABASE[name];
};
