// Normalise STR area tier to a simpler display category
export function getTierCategory(tier: STRAreaTier): "prime-str" | "selective-str" | "ltr-preferred" | "needs-verification" {
  if (tier.startsWith("Prime")) return "prime-str";
  if (tier.startsWith("Strong") || tier.startsWith("Selective")) return "selective-str";
  if (tier.startsWith("Weak")) return "ltr-preferred";
  return "needs-verification";
}

